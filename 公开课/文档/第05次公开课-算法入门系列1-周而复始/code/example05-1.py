"""
公鸡5元一只，母鸡3元一只，小鸡1元三只，用100元买一百只鸡，问公鸡、母鸡、小鸡各有多少只？
使用代数方法求解 7x + 4y = 100
"""

# x 代表公鸡数量
# y 代表母鸡数量
# z 代表小鸡数量

# 根据 7x + 4y = 100，x 的最大值是 100 // 7 = 14
for x in range(15):
    # 计算对应的 y 值
    # y = (100 - 7 * x) / 4
    numerator = 100 - 7 * x

    # 检查分子是否能被 4 整除，且 y 必须是非负数
    if numerator >= 0 and numerator % 4 == 0:
        y = numerator // 4

        # 计算小鸡数量
        z = 100 - x - y

        # 检查小鸡数量是否非负且是 3 的倍数
        if z >= 0 and z % 3 == 0:
            print(f"公鸡: {x} 只, 母鸡: {y} 只, 小鸡: {z} 只")
